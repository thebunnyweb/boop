"""Upload GGUF files + a model card to a Hugging Face model repo.

  python training/push_to_hub.py --repo bunnyweb/boop-360m-gguf runs/boop/gguf_gguf/*.gguf
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path

CARD = """---
license: apache-2.0
base_model: {base}
tags: [gguf, llama.cpp, shell, cli, bash, zsh, powershell]
---

# boop-360m — plain English → one shell command

The model behind [boop](https://github.com/thebunnyweb/boop): type what you want, get the command for your
OS and shell (macOS/zsh, Linux/bash, Windows/PowerShell). Small enough to download in seconds and answer
instantly on a laptop CPU.

```bash
pipx install boop-cli
export BOOP_MODEL={repo} BOOP_MODEL_FILE={first}
boop find pdfs over 10mb in downloads
```

| File | Size |
|---|---|
{files}

**Base model:** [{base}](https://huggingface.co/{base}) (Apache-2.0), fine-tuned with LoRA via Unsloth.

**Training data**
- Synthetic everyday tasks (files, text, archives, git, pipes) generated by boop's `data/synth.py`;
  every POSIX command was executed in a sandbox and kept only if it produced the right result.
- Examples derived from [tldr-pages](https://github.com/tldr-pages/tldr), © the tldr-pages team and
  contributors, licensed [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). Placeholders were filled
  with example values and requests were rephrased by Qwen2.5-Coder-7B-Instruct.

**Use it with boop.** boop shows every command before it runs, and risky ones (deletes, overwrites, sudo,
force-push) need you to type `yes`. Those checks are rules in boop, not something the model decides.
The model on its own can be wrong; don't pipe its output straight into a shell.
"""


def push(repo: str, ggufs: list[Path], base: str, token: str | None = None, private: bool = False) -> str:
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    api.create_repo(repo, private=private, exist_ok=True)
    for g in ggufs:
        api.upload_file(path_or_fileobj=str(g), path_in_repo=g.name, repo_id=repo)
    rows = "\n".join(f"| `{g.name}` | {g.stat().st_size / 1e6:.0f} MB |" for g in ggufs)
    card = CARD.format(base=base, repo=repo, first=ggufs[0].name, files=rows)
    api.upload_file(path_or_fileobj=card.encode(), path_in_repo="README.md", repo_id=repo)
    url = f"https://huggingface.co/{repo}"
    print(f"pushed {[g.name for g in ggufs]} → {url}")
    return url


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--base", default="HuggingFaceTB/SmolLM2-360M-Instruct")
    ap.add_argument("--private", action="store_true")
    ap.add_argument("gguf", nargs="+", type=Path)
    a = ap.parse_args()
    push(a.repo, a.gguf, a.base, os.environ.get("HF_TOKEN"), a.private)


if __name__ == "__main__":
    main()
